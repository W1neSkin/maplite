import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

/**
 * GPL and AGPL are rejected. LGPL is allowed.
 * A dual license such as "MIT OR GPL-3.0" is allowed because MIT can be chosen.
 */
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const store = join(root, "node_modules", ".pnpm")
const seen = new Map()

function licenseText(value) {
  if (typeof value === "string") return value
  if (value && typeof value === "object" && typeof value.type === "string") return value.type
  return ""
}

function isGpl(part) {
  const upper = part.toUpperCase()
  if (upper.includes("LGPL")) return false
  return upper.includes("AGPL") || upper.includes("GPL")
}

function forbidden(license) {
  const parts = license.split(/\s+OR\s+/i).map((part) => part.trim()).filter(Boolean)
  return parts.length > 0 && parts.every(isGpl)
}

function addPackage(path) {
  if (!existsSync(path)) return
  let json
  try {
    json = JSON.parse(readFileSync(path, "utf8"))
  } catch {
    return
  }
  if (!json.name || json.private) return
  let license = licenseText(json.license)
  if (!license && Array.isArray(json.licenses)) {
    license = json.licenses.map((item) => licenseText(item)).filter(Boolean).join(" OR ")
  }
  const current = seen.get(json.name)
  if (!current || license) seen.set(json.name, { license, version: json.version ?? "" })
}

if (existsSync(store)) {
  for (const entry of readdirSync(store)) {
    const modules = join(store, entry, "node_modules")
    if (!existsSync(modules)) continue
    for (const name of readdirSync(modules)) {
      if (name.startsWith("@")) {
        for (const scoped of readdirSync(join(modules, name))) {
          addPackage(join(modules, name, scoped, "package.json"))
        }
        continue
      }
      addPackage(join(modules, name, "package.json"))
    }
  }
}

const blocked = []
const unknown = []
for (const [name, item] of [...seen.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  if (!item.license) unknown.push(name)
  else if (forbidden(item.license)) blocked.push(`${name}@${item.version} (${item.license})`)
}

const lines = ["# Third-party notices", "", "Generated by scripts/check-licenses.mjs.", ""]
for (const [name, item] of [...seen.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  lines.push(`- ${name}@${item.version} — ${item.license || "unknown"}`)
}
writeFileSync(join(root, "THIRD_PARTY_NOTICES.generated.md"), `${lines.join("\n")}\n`)

if (blocked.length > 0 || unknown.length > 0) {
  if (blocked.length > 0) console.error(`GPL/AGPL dependencies:\n${blocked.join("\n")}`)
  if (unknown.length > 0) console.error(`Missing license:\n${unknown.join("\n")}`)
  process.exit(1)
}
console.log(`licenses ok (${seen.size} packages)`)
